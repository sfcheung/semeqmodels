#' @noRd
have_pars <- function(
  partables,
  pars = NULL,
  mode = c("any", "all", "none"),
  output = c("models", "partables", "logical")
) {
  # Which models in the list:
  # - has any/all/none of the parameters?
  mode <- match.arg(mode)
  mode_none <- FALSE
  if (mode == "none") {
    mode <- "any"
    mode_none <- TRUE
  }
  output <- match.arg(output)
  if (output == "models") {
    output <- "partables"
  }

  tmp <- fix_select_object(
    object = partables,
    output = output
  )
  partables <- tmp$partables
  plots_org <- tmp$plots_org
  output_tmp <- tmp$output_tmp

  if (!is.null(pars)) {
    pars_lav_list <- parse_pars_to_list(pars)
    out <- sapply(
      partables,
      has_pars_i,
      pars_lav_list = pars_lav_list,
      mode = mode
    )
    if (mode_none) {
      out <- !out
    }
  } else {
    out <- rep(TRUE, length(partables))
    names(out) <- names(partables)
  }
  out1 <- switch(
    output_tmp,
    logical = out,
    partables = partables[out]
  )
  out <- fix_select_output(
    out_original = out1,
    plots_org = plots_org,
    output = output
  )
  out
}

#' @noRd
parse_pars_to_list <- function(
  pars
) {
  # Convert model syntax to a list of one-row parameter tables
  pars_lav <- lavaan::lavParseModelString(
    pars,
    as.data.frame. = TRUE,
    warn = FALSE
  )
  pars_lav_list <- split(
    pars_lav,
    seq_len(nrow(pars_lav))
  )
  pars_lav_list
}

#' @noRd
has_pars_i <- function(
  partable,
  pars_lav_list,
  mode = c("any", "all")
) {
  # Does a model have any/all of parameter pars?
  mode <- match.arg(mode)
  out0 <- sapply(
    pars_lav_list,
    has_par_i,
    partable = partable
  )
  if (mode == "any") {
    out1 <- any(out0)
  } else if (mode == "all") {
    out1 <- all(out0)
  }
  out1
}

#' @noRd
has_par_i <- function(
  partable,
  par
) {
  # Does a model have parameter par as a free parameter?
  # partable is a parameter table of a model
  # par must be a one-row parameter table
  op <- par$op
  if (op == "~~") {
    i1 <- (partable$op == par$op) &
          (partable$lhs == par$lhs) &
          (partable$rhs == par$rhs) &
          (partable$free > 0)
    i2 <- (partable$op == par$op) &
          (partable$lhs == par$rhs) &
          (partable$rhs == par$lhs) &
          (partable$free > 0)
    out <- any(i1 | i2)
  } else {
    i1 <- (partable$op == par$op) &
          (partable$lhs == par$lhs) &
          (partable$rhs == par$rhs) &
          (partable$free > 0 )
    out <- any(i1)
  }
  isTRUE(out)
}

#' @details
#'
#' ## Select by covariances with an error term
#'
#' The function [remove_x_y_ecov()]
#' removes models from `partables` that
#' have a covariance between
#' an observed or latent variable
#' (or its error term) and the error
#' term of another variable it predicts,
#' either directly or indirectly.
#'
#' @param cl A cluster created by
#' [parallel::makeCluster()]. Used
#' internally. Do not set this argument.
#'
#' @rdname partable_select
#' @export
remove_x_y_ecov <- function(
  partables,
  output = c("models", "partables", "logical"),
  cl = NULL
) {
  output <- match.arg(output)
  tmp <- fix_select_object(
    object = partables,
    output = output
  )
  partables <- tmp$partables
  plots_org <- tmp$plots_org
  output_tmp <- tmp$output_tmp

  # chk <- sapply(
  #           partables,
  #           has_x_y_ecov
  #         )
  if (!is.null(cl)) {
    chk <- parallel::parSapplyLB(
      cl = cl,
      partables,
      has_x_y_ecov2
    )
  } else {
    chk <- sapply(
              partables,
              has_x_y_ecov2
            )
  }
  # chk <- sapply(
  #           partables,
  #           has_x_y_ecov2
  #         )
  # chk <- chk | chk2
  if (output_tmp == "logical") {
    out0 <- !chk
    names(out0) <- names(partables)
  }
  if (any(chk)) {
    tmp <- class(partables)
    out0 <- partables[!chk]
    class(out0) <- tmp
  } else {
    tmp <- class(partables)
    out0 <- partables
    class(out0) <- tmp
  }
  out <- fix_select_output(
    out_original = out0,
    plots_org = plots_org,
    output = output
  )
  out
}

#' @details
#'
#' ## Select by the role of a variable
#'
#' The function [must_not_be_y()]
#' keeps only models with selected variables
#' (observed or latent) not
#' appearing as the outcome in a
#' regression equation (indicators
#' not counted). They are
#' defined as variables not
#' in `"eqs.y"`
#' as returned by [lavaan::lavNames()].
#'
#' @param vars A character vector of
#' variables to be checked.
#'
#' @examples
#'
#' # === must_not_be_y ====
#'
#' must_not_be_y(partables1, c("fx"))
#' must_not_be_y(partables1, c("fx"),
#'               output = "logical")
#'
#'
#' @rdname partable_select
#' @export
must_not_be_y <- function(
  partables,
  vars = NULL,
  output = c("models", "partables", "logical")
) {
  output <- match.arg(output)
  tmp <- fix_select_object(
    object = partables,
    output = output
  )
  partables <- tmp$partables
  plots_org <- tmp$plots_org
  output_tmp <- tmp$output_tmp

  chk <- sapply(
            partables,
            vars_is_eqsy,
            vars = vars
          )
  chk <- !chk
  if (output_tmp == "logical") {
    out0 <- chk
    names(out0) <- names(partables)
  } else {
    out0 <- partables[chk]
    class(out0) <- class(partables)
  }

  out <- fix_select_output(
    out_original = out0,
    plots_org = plots_org,
    output = output
  )
  out
}


