#' @noRd
has_x_to_y <- function(
  partable,
  y_on_x,
  mode = c("any", "all")
) {
  mode <- match.arg(mode)
  out <- sapply(
    y_on_x,
    has_x_to_y_i,
    partable = partable
  )
  out <- switch(
    mode,
    any = any(out),
    all = all(out)
  )
  out
}

#' @noRd
has_x_to_y_i <- function(
  partable,
  y_on_x
) {
  y_on_x_pt <- lavaan::lavParseModelString(
            y_on_x,
            as.data.frame. = TRUE
            )
  x <- y_on_x_pt$rhs
  y <- y_on_x_pt$lhs
  fit0 <- auto_ram(
    FUN = lavaan::sem,
    model = partable,
    do.fit = FALSE,
    fixed.x = FALSE
  )
  chk1 <- tryCatch(
            suppressWarnings(manymome::all_indirect_paths(
              fit = fit0,
              x = x,
              y = y
            )),
            error = function(e) e
          )
  if (inherits(chk1, "error")) {
    i1 <- FALSE
  } else {
    i1 <- length(chk1) > 0
  }
  chk2 <- has_par_i(
    partable,
    par = y_on_x_pt
  )
  i2 <- chk2
  any(i1, i2)
}

#' @noRd
partabes_from_plots <- function(
  object
) {
  out <- lapply(
    object,
    attr,
    which = "partable",
    exact = TRUE
  )
  out
}

#' @noRd
overwrite_attributes <- function(
  object,
  source_object,
  exclude = c("names")
) {
  a_names <- names(attributes(source_object))
  b_names <- setdiff(a_names, exclude)
  if (length(b_names) == 0) {
    return(object)
  }
  for (x in b_names) {
    attr(object,
         x) <- attr(
                  source_object,
                  x,
                  exact = TRUE
                )
  }
  object
}

#' @noRd
fix_select_object <- function(
  object,
  output
) {
  if (inherits(object, "partables_plots")) {
    plots_org <- object
    partables <- partabes_from_plots(plots_org)
    if (output %in% c("models", "partables")) {
      output_tmp <- "logical"
    }
  } else {
    partables <- object
    plots_org <- NULL
    output_tmp <- output
  }
  list(partables = partables,
       plots_org = plots_org,
       output_tmp = output_tmp)
}

#' @noRd
fix_select_output <- function(
  out_original,
  plots_org,
  output
) {
  if (!is.null(plots_org)) {
    if (output %in% c("models", "partables")) {
      out <- plots_org[out_original]
      out <- overwrite_attributes(
                out,
                plots_org
              )
    } else {
      out <- out_original
    }
  } else {
    out <- out_original
  }
  out
}
