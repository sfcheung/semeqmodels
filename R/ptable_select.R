#' @title Select Models (Parameter Tables)
#'
#' @description Helper functions to
#' select models (parameter tables) based on
#' various criteria.
#'
#' @return
#' Each of the select functions, by default,
#' returns a list of parameter tables (models)
#' that meet the criterion of that function,
#' or a list of plots of the parameter tables
#' if `partables` is the output of [partables_plots()].
#' If `output` is set to `"logical"`,
#' each of these functions returns
#' a logical vector to indicate models or plots
#' that meet the criterion. The vector
#' can then be used to extract objects meeting
#' the criterion.
#'
#' @name partable_select
NULL

#' @details
#'
#' The select functions can be used both
#' for a list of models in the form
#' of parameter tables (the output
#' of [lavaan::parameterTable()]) or
#' a list of plots based on these models,
#' generated by [partables_plots()].
#' They return an object of the same type.
#' Therefore, they can be used to filter
#' both models and plots of models.
#'
#' ## Select by free parameters
#'
#' The function
#' [have_pars_all()] selects models
#' that have all the free parameters
#' specified in `pars`.
#'
#' @param partables A list of parameter
#' tables, such as a
#' `partables` or `eq_partables` object.
#' It can also be the output of
#' [partables_plots()].
#'
#' @param pars A character vector
#' of `lavaan` model syntax that
#' can be converted to a parameter table.
#' It can be a vector of parameters,
#' such as `c("y ~ x", "m ~~ x")`, but
#' can also be of other forms as long
#' as `lavaan::lavParseModelString()`
#' can process it. Covariances such as
#' `"m ~~ x"` and `"x ~~ m"` are treated
#' as the same and so only one of them
#' is necessary.
#'
#' @param output The type of output.
#' If `"models"` or `"partables"`,
#' the output is a subset of the `partables`, which
#' can be a list of parameter tables
#' or a list of plots of parameter tables.
#' If `"logical"`, a
#' logical vector of the same length as
#' `partables` is returned to indicate
#' models that match the selection
#' criteria.
#'
#' @examples
#'
#' library(lavaan)
#'
#' # Model 1
#'
#' mod1 <-
#' "
#' fx =~ x1 + x2 + x3
#' fm =~ m1 + m2 + m3
#' fy =~ y1 + y2 + y3
#' fm ~ fx
#' fy ~ fm + fx
#' "
#' fit1 <- sem(
#'           model = mod1,
#'           data = data_test_3_factor_3_item
#'         )
#' fit1_1_more <- drop_k(fit1)
#' fit1_1_more_1_less <- lapply(
#'   fit1_1_more,
#'   add_k
#' )
#'
#' partables1 <- combine_partables(fit1_1_more_1_less)
#' partables1
#'
#' # === have_pars_all ====
#'
#' have_pars_all(partables1, c("fx ~~ fm", "fy ~ fx"))
#' have_pars_all(partables1, c("fx ~~ fm", "fy ~ fx"),
#'               output = "logical")
#'
#' @rdname partable_select
#' @export
have_pars_all <- function(
  partables,
  pars = NULL,
  output = c("models", "partables", "logical")
) {
  output <- match.arg(output)
  tmp <- fix_select_object(
    object = partables,
    output = output
  )
  partables <- tmp$partables
  plots_org <- tmp$plots_org
  output_tmp <- tmp$output_tmp

  out0 <- have_pars(
    partables = partables,
    pars = pars,
    mode = "all",
    output = output_tmp
  )
  out <- fix_select_output(
    out_original = out0,
    plots_org = plots_org,
    output = output
  )
  out
}

